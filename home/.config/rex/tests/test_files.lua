local T = dofile("tests/rex_test.lua")
local fs = T.fs

T.test("paths retain boundaries, spaces and root semantics", function()
  assert(fs.parent("/tmp") == "/" and fs.parent("/") == "/")
  assert(fs.parent("/one/two/") == "/one" and fs.name("/one/two/") == "two")
  assert(fs.under("/one/two", "/one") and not fs.under("/one-more", "/one"))
  assert(fs.under("/one", "/one") and fs.under("/one", "/"))
end)

T.test("resolve handles physical, missing and symbolic paths without GNU flags", function()
  local root = T.temp()
  fs.run({ "mkdir", "-p", root .. "/real dir" })
  fs.run({ "ln", "-s", "real dir", root .. "/link" })
  assert(fs.resolve(root .. "/link") == root .. "/real dir")
  assert(fs.resolve(root .. "/link/missing/child") == root .. "/real dir/missing/child")
  assert(fs.resolve(root .. "/link/missing/../child") == root .. "/real dir/child")
  assert(fs.resolve(root .. "/link/../new") == root .. "/new")
  fs.run({ "ln", "-s", "second", root .. "/first" })
  fs.run({ "ln", "-s", "first", root .. "/second" })
  T.raises("Too many symbolic links", function() fs.resolve(root .. "/first") end)
end)

T.test("filesystem arguments with shell syntax stay data", function()
  local root = T.temp()
  local path = root .. "/quote' $(touch BAD) `echo no`"
  T.write(path .. "/file\nname", "keep")
  assert(fs.resolve(path) == path)
  local entries = fs.entries(path)
  assert(#entries == 1 and entries[1] == path .. "/file\nname")
  assert(fs.read(entries[1]) == "keep" and not fs.test("-e", root .. "/BAD"))
end)

T.test("command failures and launch failures propagate", function()
  T.raises("diagnostic", function() fs.run({ "/bin/sh", "-c", "echo diagnostic >&2; exit 4" }) end)
  T.raises("missing-rex-test-command", function() fs.run({ "/missing-rex-test-command" }) end)
  assert(not fs.test("-e", "/missing-rex-test-file"))
  local ok, err = pcall(fs.run, { "/bin/sh", "-c", "echo details; echo summary >&2; exit 4" })
  assert(not ok and err:find("details", 1, true) and err:find("summary", 1, true))
end)
